/**
 * Get a translation by key and language
 * @param {string} key
 * @param {'bg'|'en'} lang
 * @returns {string}
 */
export function translate(key, lang = 'bg') {
  const entry = translations[key]
  if (!entry) { console.warn(`[i18n] missing key: ${key}`); return key }
  return entry[lang] || entry['bg'] || key
}
